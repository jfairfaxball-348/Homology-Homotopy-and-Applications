#!/usr/bin/env python3
"""Exhaustively check ONLY the 12-element abstract shear action.
This script does NOT certify any stable stem, CW map or Top interleaving."""
import hashlib
import json

n = 12
classes = set(range(n))
orbits = []
for x in range(n):
    orbit = sorted({(x + 2*j) % n for j in range(n)})
    assert len(orbit) == 6
    if orbit not in orbits:
        orbits.append(orbit)
assert sorted(orbits) == [[0, 2, 4, 6, 8, 10], [1, 3, 5, 7, 9, 11]]
assert set.union(*(set(o) for o in orbits)) == classes
for x in classes:
    for j in classes:
        assert ((x+2*j)%n)%2 == x%2
cert = {"indeterminacy_quotient":"Z/24 divided by subgroup generated by 12",
        "modulus":n,"orbits":sorted(orbits),"shear_step":2}
wire = json.dumps(cert,sort_keys=True,separators=(",",":"))
digest=hashlib.sha256(wire.encode()).hexdigest()
assert digest=="a75bef9333009c51354fdd26cc6d8b02dbe11b3e9c82a21f27631e7aae2f631d"
print(wire)
print("SHA256",digest)
print("PASS exact 12 by 12 arithmetic; no topological certification")
